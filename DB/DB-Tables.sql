CREATE INDEX idx_det_venta_item ON Detalle_Venta (id_item);

-- === Índices: Inventario_Sedes ===
-- Búsqueda de stock de un item específico en todas las sedes.
CREATE INDEX idx_inv_item ON Inventario_Sedes (id_item);

